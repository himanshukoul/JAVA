    private static String[] wordxor(String w1[], String w2[]) {
        String res[] = new String[4];
        for (int i = 0; i < 4; i++) {
            int a = Integer.parseInt(w1[i], 16);
            int b = Integer.parseInt(w2[i], 16);
            res[i] = hex2Places(Integer.toHexString(a ^ b));
        }
        return res;
    }

    private static String hex2Places(String hx) {
        if (hx.length() < 2)
            return "0" + hx;
        return hx;
    }

