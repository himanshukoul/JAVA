    private static int xtime(int x) {
        x = x << 1;
        if ((x & 0x100) != 0) {
            x ^= 0x11B;
        }
        return x & 0xFF;
    }

    private static int gfMult(int a, int b) {
        int result = 0;
        while (a != 0) {
            if ((a & 1) != 0) {
                result ^= b;
            }
            b = xtime(b);
            a >>= 1;
        }
        return result;
    }

    private static String[][] mixColumns(String[][] state, int inv) {
        int[][] result = new int[4][4];
        int[] matrix = (inv == -1) ? stndMat : invStndMat;

        for (int col = 0; col < 4; col++) {
            for (int row = 0; row < 4; row++) {
                int val = 0;
                for (int k = 0; k < 4; k++) {
                    int factor = matrix[row * 4 + k];
                    int b = Integer.parseInt(state[k][col], 16);
                    val ^= gfMult(factor, b);
                }
                result[row][col] = val;
            }
        }
        String[][] hexRes = new String[4][4];
        for (int i = 0; i < 4; i++) {
            for (int j = 0; j < 4; j++) {
                hexRes[i][j] = hex2Places(Integer.toHexString(result[i][j]));
            }
        }
        return hexRes;
    }

    private static String[][] addRoundKey(String[][] state, String[][] words, int round) {
        String[][] res = new String[4][4];
        int keyStartIndex = round * 4;
        for (int col = 0; col < 4; col++) {
            int wordIndex = keyStartIndex + col;
            for (int row = 0; row < 4; row++) {
                int stateByte = Integer.parseInt(state[row][col], 16);
                int keyByte = Integer.parseInt(words[wordIndex][row], 16);
                int xored = stateByte ^ keyByte;
                res[row][col] = hex2Places(Integer.toHexString(xored));
            }
        }
        return res;
    }

