    private static String[][] shiftRows(String arr[][], int inv) {
        String res[][] = new String[4][4];
        for (int i = 0; i < 4; i++) {
            for (int j = 0; j < 4; j++) {
                int temp = j - i;
                if (temp < 0)
                    temp += 4;
                res[i][j] = inv == -1 ? arr[i][(j + i) % 4] : arr[i][temp % 4];
            }
        }
        return res;
    }

